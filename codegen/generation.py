"""A host's families under ``aklr/plugins/<host>/``, generated from main's tree by the host's adaptations."""

from __future__ import annotations

import importlib
import importlib.util
import io
import json
import shutil
import subprocess
import sys
import tarfile
import tempfile
import types
from collections.abc import Sequence
from pathlib import Path

import aklr
from aklr.core.contract import op
from aklr.core.contract.op import OpContract
from aklr.core.contract.spec import contract_name
from codegen.adaptation import Adaptation
from codegen.contract_source import ContractSource

__all__ = ["Generation"]

_LICENSE = "# SPDX-License-Identifier: MIT\n# Copyright (C) 2025-2026, Advanced Micro Devices, Inc. All rights reserved.\n"
# main's modules that are not copied: the contract is re-cut, and nothing calls an api function
_NOT_COPIED = ("contract.py", "api.py", "__init__.py")


class Generation:
    """The families of ``host`` that ``adaptations`` make of main's contracts under ``source`` (a
    directory of main, as ``aklr/ops``), and of main's small Points in ``cases`` (a file of main)."""

    def __init__(self, host: str, source: str, cases: str, adaptations: Sequence[Adaptation]) -> None:
        self.host, self.source, self.cases, self.adaptations = host, source, cases, tuple(adaptations)
        self.root = Path(aklr.__file__).parents[1]
        self.host_dir = self.root / "aklr" / "plugins" / host
        self.package = f"aklr.plugins.{host}"

    def write(self, rev: str) -> list[str]:
        """Generate the families from main at the git revision ``rev`` into this checkout, in place of
        the ones generated before: each family's contract.py (its statements at the bottom), reference.py, baseline.py and
        schema files, main's modules they stand on under ``_main/``, and ``tests/plugins/<host>/cases.py``.
        Returns main's schema files that no adaptation takes."""
        sha = subprocess.run(
            ["git", "-C", self.root, "rev-parse", "--short", rev], check=True, capture_output=True, text=True
        ).stdout.strip()
        mark = (
            f'"""Generated by `python -m codegen.{self.host}` from main at {sha}: run it again, do not edit.'
        )
        header = f"{_LICENSE}# ruff: noqa\n# fmt: off\n{mark}"
        archive = subprocess.run(
            ["git", "-C", self.root, "archive", rev, self.source, self.cases], check=True, capture_output=True
        ).stdout
        with tempfile.TemporaryDirectory() as tmp:
            tree = Path(tmp)
            with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
                tar.extractall(tree, filter="data")
            # the families generated before go; each new one is there before its contract names it
            for directory in [self.host_dir / "_main", *self.host_dir.iterdir()]:
                contract_py = directory / "contract.py"
                if directory.name == "_main" or (
                    contract_py.is_file() and '"""Generated by' in contract_py.read_text()
                ):
                    shutil.rmtree(directory, ignore_errors=True)
            families = dict.fromkeys(a.family for a in self.adaptations)
            for family in families:
                (self.host_dir / family / "impls").mkdir(parents=True)
                (self.host_dir / family / "__init__.py").write_text(_LICENSE)
                (self.host_dir / family / "contract.py").write_text(f'{header}"""\nCONTRACTS = ()\n')
            mains = self._main_contracts(tree)
            recut = [(a, *mains[a.source], a.contract(mains[a.source][0])) for a in self.adaptations]
            taken: set[Path] = set()
            for family in families:
                self._write_family(tree, family, [r for r in recut if r[0].family == family], header, taken)
            copied = dict.fromkeys(main_dir for _, _, main_dir, _ in recut)
            for main_dir in copied:
                target = self.host_dir / "_main" / main_dir.relative_to(tree / self.source)
                target.mkdir(parents=True, exist_ok=True)
                for path in sorted(p for p in main_dir.glob("*.py") if p.name not in _NOT_COPIED):
                    text = path.read_text().replace(
                        self.source.replace("/", ".") + ".", f"{self.package}._main."
                    )
                    (target / path.name).write_text(text)
            for directory in [
                self.host_dir / "_main",
                *(p for p in (self.host_dir / "_main").rglob("*") if p.is_dir()),
            ]:
                (directory / "__init__.py").write_text(_LICENSE)
            self._write_cases(tree, recut, header)
            schemas = sorted((tree / self.source).rglob("impls/*/*/*.json"))
            return [str(path.relative_to(tree)) for path in schemas if path not in taken]

    def _main_contracts(self, tree: Path) -> dict[str, tuple[OpContract, Path]]:  # structure: allow S4 write is long, and this is how main's code is read  # fmt: skip
        """Main's contracts under ``tree``, by id, each with its family's directory. Main's contract
        modules are imported as they are, their contracts unchecked: main writes them for its own core."""
        before, contracts = set(sys.modules), {}
        checked, op.OpContract = op.OpContract, OpContract.model_construct
        try:
            for path in sorted((tree / self.source).rglob("contract.py")):
                parts = path.relative_to(tree).with_suffix("").parts
                for depth in range(1, len(parts)):
                    name = ".".join(parts[:depth])
                    if name not in sys.modules and importlib.util.find_spec(name) is None:
                        # a package of main this checkout lacks, without running its __init__
                        package = sys.modules[name] = types.ModuleType(name)
                        package.__path__ = [str(tree.joinpath(*parts[:depth]))]
                for unchecked in importlib.import_module(".".join(parts)).CONTRACTS:
                    fields = {name: getattr(unchecked, name) for name in OpContract.model_fields}
                    out = fields["outputs"].get("out")
                    if out is not None and out.dtype.param_name is None:
                        # main's core gave an output named out the dtype param out_dtype
                        dtype = out.dtype.model_copy(update={"param_name": "out_dtype"})
                        fields["outputs"] = {
                            **fields["outputs"],
                            "out": out.model_copy(update={"dtype": dtype}),
                        }
                    # a new object: one main's module has used holds what it derived before
                    main = OpContract.model_construct(**fields)
                    contracts[main.contract_id] = (main, path.parent)
        finally:
            op.OpContract = checked
            # main's modules go again; what else they made python import (torch) stays imported
            for name in set(sys.modules) - before:
                module = sys.modules[name]
                origin = getattr(module, "__file__", None) or next(iter(getattr(module, "__path__", [])), "")
                if Path(origin).is_relative_to(tree):
                    del sys.modules[name]
        return contracts

    def _write_family(  # structure: allow S4 write is long, and a family is its unit of output
        self,
        tree: Path,
        family: str,
        recut: list[tuple[Adaptation, OpContract, Path, OpContract]],
        header: str,
        taken: set[Path],
    ) -> None:
        """Write ``family``: the re-cut contracts of ``recut`` (each adaptation, main's contract, its
        directory and the re-cut one), their references and baselines over main's, the statements of
        those a host target takes, and main's schema files under them; ``taken`` gains each one taken."""
        directory = self.host_dir / family
        names = [contract_name(contract.contract_id).upper() for *_, contract in recut]
        reference_py = f'{header}\n\nThe references of the {family} family: main\'s, under each contract\'s names."""\n\nfrom types import SimpleNamespace\n\n'
        baseline_py = (
            f'{header}\n\nThe baselines of the {family} family: main\'s, under each contract\'s names."""\n\n'
        )
        references, baselines, statements = "", "", ""
        reference_imports, baseline_imports = {}, {}  # each of main's functions once, in order
        for (adaptation, main, main_dir, contract), name in zip(recut, names, strict=True):
            old = contract_name(main.contract_id)
            main_package = ".".join((self.package, "_main", *main_dir.relative_to(tree / self.source).parts))
            if f"def {old}_reference(" in (main_dir / "reference.py").read_text():
                reference_imports[
                    f"from {main_package}.reference import {old}_reference as main_{old}_reference\n"
                ] = None
                references += adaptation.reference_source(main, contract)
            baseline = main_dir / "baseline.py"
            if baseline.is_file() and f"def {old}_baseline(" in baseline.read_text():
                baseline_imports[
                    f"from {main_package}.baseline import {old}_baseline as main_{old}_baseline\n"
                ] = None
                baselines += adaptation.baseline_source(main, contract)
            if adaptation.target is not None:
                versions = ", ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in adaptation.versions)
                trailing = "," if len(adaptation.versions) == 1 else ""
                statements += f'plugin.declare("{adaptation.target}", {name}, "impls", versions=({versions}{trailing}))\n'
            for path in sorted(main_dir.glob("impls/*/*/*.json")):
                main_schema = json.loads(path.read_text())
                if main_schema["contract_id"] != main.contract_id:
                    continue
                schema = adaptation.schema(main_schema, main, contract)
                if schema is None:
                    continue
                written = directory / schema.relative_path()
                if errors := contract.schema_errors(written.relative_to(self.root), schema):
                    raise ValueError("\n".join(errors))
                written.parent.mkdir(parents=True, exist_ok=True)
                written.write_text(schema.schema_text())
                taken.add(path)
        contracts = {name: contract for name, (*_, contract) in zip(names, recut, strict=True)}
        source = ContractSource(contracts).text()
        if statements:
            # the family's statements, at the bottom of its contract.py
            imports, _, assignments = source.partition("\n\n")
            source = f"{imports}\nfrom {self.package} import plugin\n\n{assignments}\n{statements}"
        docstring = f"The contracts of the {family} family, and the host targets they describe."
        (directory / "contract.py").write_text(f'{header}\n\n{docstring}"""\n\n{source}')
        written = importlib.import_module(f"{self.package}.{family}.contract").CONTRACTS
        if written != tuple(contracts.values()):
            raise ValueError(f"{directory / 'contract.py'} does not build the contracts it was written from")
        (directory / "reference.py").write_text(reference_py + "".join(reference_imports) + references)
        if baselines:
            (directory / "baseline.py").write_text(baseline_py + "".join(baseline_imports) + baselines)

    def _write_cases(self, tree: Path, recut: list[tuple[Adaptation, OpContract, Path, OpContract]], header: str) -> None:  # structure: allow S4 write is long, and the cases are another file of main  # fmt: skip
        """Write ``tests/plugins/<host>/cases.py``: main's small Points, each under every re-cut contract
        that holds it, and which of them the backend runs on gfx950 only."""
        spec = importlib.util.spec_from_file_location("main_cases", tree / self.cases)
        main_cases = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(main_cases)
        points, gfx950, gfx950_variants = [], set(), set()
        for adaptation, main, _, contract in recut:
            for main_point in main_cases.SMALL_POINTS:
                if main_point.contract_id == main.contract_id:
                    point = adaptation.point(main_point, contract)
                    if point is not None:
                        points.append(point)
            if main.contract_id in main_cases.GFX950_CONTRACT_IDS:
                gfx950.add(contract.contract_id)
            for main_id, variant in main_cases.GFX950_LAYOUT_VARIANTS:
                if main_id == main.contract_id and adaptation.pin.get("layout_variant") == variant:
                    gfx950.add(contract.contract_id)
                elif main_id == main.contract_id and "layout_variant" not in adaptation.pin:
                    gfx950_variants.add((contract.contract_id, variant))
        text = (
            f'{header}\n\nThe small Points of the aklr/plugins/{self.host} contracts (``tests.op_case.OpCase``)."""\n\n'
            "from aklr.core.contract.spec import PointSpec\n\n"
            "# each contract's base Point first\nSMALL_POINTS: tuple[PointSpec, ...] = (\n"
            + "".join(f"    {point!r},\n" for point in points)
            + ")\n# the contracts whose backend runs only on gfx950\n"
            + f"GFX950_CONTRACT_IDS = frozenset({sorted(gfx950)!r})\n"
            + "# layout variants whose backend runs only on gfx950, of contracts whose other Points run anywhere\n"
            + f"GFX950_LAYOUT_VARIANTS = frozenset({sorted(gfx950_variants)!r})\n"
        )
        (self.root / "tests" / "plugins" / self.host / "cases.py").write_text(text)
